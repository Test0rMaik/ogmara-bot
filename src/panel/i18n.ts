/**
 * The panel's translation tables.
 *
 * No i18n library: the panel is a dependency-free, no-build-step page (see the
 * module comment in `ui.ts`), so this is a plain object embedded into the
 * generated script as JSON, with a small `t(key, vars)` lookup written
 * alongside it. English is authoritative — every other locale is checked
 * against its key set in `i18n.test.ts`, so a key that exists in one locale
 * and not another fails a test instead of silently falling back at runtime.
 *
 * Scope: this translates the interface CHROME — labels, buttons, headings,
 * confirmations, status text. It does not translate diagnostic text that
 * passes through verbatim from the server (`err.message` from a failed
 * fetch, a Zod validation issue) — that boundary already exists in this panel
 * (`showError(err.message)`) and extending it would mean translating strings
 * this process does not own and cannot keep in sync.
 */

